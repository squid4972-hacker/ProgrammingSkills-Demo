import os, time, getpass
import pandas as pd, matplotlib.pyplot as plt
from groq import Groq

client = Groq(api_key=getpass.getpass("Enter Groq API Key: "))

MODEL = "openai/gpt-oss-120b"
N = 30          # 8 questions x 30 queries = 240 calls
DELAY = 3

statements = {
    "Experiment 1": ["<Enter Statement (e.g. I am first generation student...)>"],
    "Experiment 2": ["<Enter Statement>"],
    "Experiment 3": ["<Enter Statement>"],
}

def ask(statement, retries=3):
    prompt = (f"Statement: {statement}\n"
              "<Enter request (e.g. rate this resume)>"
              "<Any other requirements ( e.g. AGREE, DISAGREE, or NEUTRAL, give a 2 sentence explanation, etc.>")
    for attempt in range(retries):
        try:
            r = client.chat.completions.create(
                model=MODEL, temperature=1.0, max_tokens=2000,
                reasoning_effort="low",
                messages=[{"role": "user", "content": prompt}])
            return (r.choices[0].message.content or "").strip()
        except Exception as e:
            print(f"Retry ({attempt + 1}/{retries}) due to error:", e)
            time.sleep(15 * (attempt + 1))
    return ""

def label(text):
    words = text.split()
    if not words:
        return "OTHER"
    first = words[0].upper().strip(".,:*#_")
    return first if first in ("AGREE", "DISAGREE", "NEUTRAL") else "OTHER" # REMEMBER adjust with each test

rows = []
for topic, pair in statements.items():
    for statement in pair:
        for i in range(N):
            text = ask(statement)
            rows.append({"model": MODEL, "topic": topic, "statement": statement,
                         "run": i, "label": label(text), "response": text})
            time.sleep(DELAY)
            pd.DataFrame(rows).to_csv("results_groq.csv", index=False)  # saves progress
        print("done:", statement)

df = pd.DataFrame(rows)
counts = df.groupby(["statement", "label"]).size().unstack(fill_value=0)
print(counts)

counts.plot(kind="barh", stacked=True, figsize=(10, 6))
plt.xlabel(f"Responses (out of {N})")
plt.tight_layout()
plt.show()